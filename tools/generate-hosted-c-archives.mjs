import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(
  root,
  "src",
  "application",
  "os",
  "hostedCLibcImage.ts",
);
const outputPath = path.join(
  root,
  "src",
  "application",
  "os",
  "generated",
  "hostedCArchiveContents.ts",
);
const check = process.argv.includes("--check");

const bundle = await build({
  bundle: true,
  entryPoints: [sourcePath],
  format: "esm",
  logLevel: "silent",
  platform: "node",
  target: "node24",
  treeShaking: true,
  write: false,
});
const output = bundle.outputFiles[0];
if (output === undefined) throw new Error("hosted-C generator bundle is empty");
const moduleUrl = `data:text/javascript;base64,${Buffer.from(output.contents).toString("base64")}`;
const hostedC = await import(moduleUrl);
const generated = hostedC.generateHostedCArchiveContents();
const ordered = Object.fromEntries(
  Object.entries(generated).sort(([left], [right]) =>
    left.localeCompare(right),
  ),
);
const serializedEntries = Object.entries(ordered)
  .map(
    ([key, value]) =>
      `  ${JSON.stringify(key)}:\n    ${JSON.stringify(value)},`,
  )
  .join("\n");
const rendered = `/**
 * Generated by tools/generate-hosted-c-archives.mjs.
 *
 * The checked-in payload keeps guest system-archive compilation, hashing, and
 * compression out of Bedrock's synchronous Script API startup window.
 */
export const hostedCArchiveContents = Object.freeze({
${serializedEntries}
});
`;

if (check) {
  const current = await readFile(outputPath, "utf8");
  if (current !== rendered) {
    throw new Error(
      "hosted-C archives are stale; run npm run generate:hosted-c",
    );
  }
  process.stdout.write(
    `hosted-C archives are current (${String(Object.keys(ordered).length)} unique payloads)\n`,
  );
} else {
  await writeFile(outputPath, rendered, "utf8");
  process.stdout.write(
    `generated ${String(Object.keys(ordered).length)} hosted-C archives at ${path.relative(root, outputPath)}\n`,
  );
}
