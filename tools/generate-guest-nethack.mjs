import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { build } from "esbuild";
import { format } from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(
  root,
  "src",
  "application",
  "toolchain",
  "guestNethackBuilder.ts",
);
const outputPath = path.join(
  root,
  "src",
  "application",
  "toolchain",
  "generated",
  "guestNethackExecutableContents.ts",
);
const check = process.argv.includes("--check");

const bundle = await build({
  bundle: true,
  entryPoints: [sourcePath],
  format: "esm",
  logLevel: "silent",
  platform: "node",
  target: "node24",
  treeShaking: true,
  write: false,
});
const output = bundle.outputFiles[0];
if (output === undefined) throw new Error("NetHack generator bundle is empty");
const moduleUrl = `data:text/javascript;base64,${Buffer.from(output.contents).toString("base64")}`;
const builder = await import(moduleUrl);
const executable = builder.buildGuestNethackExecutable();
const contents = `CS486\n${JSON.stringify(executable)}`;
const unformatted = `/**
 * Generated by tools/generate-guest-nethack.mjs.
 *
 * The checked-in payload keeps guest compilation, linking, validation, and
 * serialization out of Bedrock's synchronous Script API startup window.
 */
export const guestNethackExecutableContents = ${JSON.stringify(contents)};
`;
const rendered = await format(unformatted, { parser: "typescript" });

if (check) {
  const current = await readFile(outputPath, "utf8");
  if (current !== rendered) {
    throw new Error(
      "guest NetHack executable is stale; run npm run generate:guest-nethack",
    );
  }
  process.stdout.write(
    `guest NetHack executable is current (${String(Buffer.byteLength(contents))} bytes)\n`,
  );
} else {
  await writeFile(outputPath, rendered, "utf8");
  process.stdout.write(
    `generated ${String(Buffer.byteLength(contents))}-byte guest NetHack executable at ${path.relative(root, outputPath)}\n`,
  );
}
